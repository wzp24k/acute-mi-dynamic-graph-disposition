"""Build the eICU hospital-heterogeneity report from locked results.

This script performs secondary aggregation only. It does not fit, refit, or
recalibrate any model. Sources are the locked eICU cohort, site metrics, and
patient-safe hospital-cluster audit generated by the transport analysis.
"""
from __future__ import annotations

import hashlib
import json
from datetime import datetime, timezone
from pathlib import Path

import numpy as np
import pandas as pd


PROJECT_ROOT = Path(__file__).resolve().parents[1]
COHORT_PATH = PROJECT_ROOT / "data" / "processed" / "eicu" / "cohort.csv"
SITE_METRICS_PATH = PROJECT_ROOT / "results" / "tables" / "eicu_site_metrics.csv"
SITE_AUDIT_PATH = PROJECT_ROOT / "results" / "audits" / "eicu_site_analysis.json"
CSV_PATH = (
    PROJECT_ROOT
    / "results"
    / "tables"
    / "tableS12_eicu_site_heterogeneity.csv"
)
MD_PATH = (
    PROJECT_ROOT
    / "results"
    / "tables"
    / "tableS12_eicu_site_heterogeneity.md"
)
JSON_PATH = (
    PROJECT_ROOT
    / "results"
    / "audits"
    / "eicu_site_heterogeneity_report.json"
)

PRIMARY_MODEL = "dggru_tr"
MODEL_LABELS = {
    "dggru_tr": "DG-GRU+TR",
    "xgb_static": "XGB-static",
    "xgb_static_ts": "XGB-static+TS",
}
MODEL_ORDER = ["dggru_tr", "xgb_static", "xgb_static_ts"]


def sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def require(condition: bool, message: str) -> None:
    if not condition:
        raise ValueError(message)


def round_or_none(value: float | int | None, digits: int = 10) -> float | None:
    if value is None or not np.isfinite(value):
        return None
    return round(float(value), digits)


def summarize_site_auc(
    site_table: pd.DataFrame, model: str
) -> dict[str, float | int | str]:
    frame = site_table.loc[site_table["model"].eq(model)].copy()
    require(not frame.empty, f"No site metrics found for {model}")
    valid = frame.loc[frame["macro_auc"].notna()].copy()
    require(not valid.empty, f"No computable site macro-AUC values for {model}")

    values = valid["macro_auc"].astype(float)
    q1 = float(values.quantile(0.25, interpolation="linear"))
    median = float(values.quantile(0.50, interpolation="linear"))
    q3 = float(values.quantile(0.75, interpolation="linear"))
    worst = valid.loc[valid["macro_auc"].idxmin()]
    best = valid.loc[valid["macro_auc"].idxmax()]

    return {
        "n_hospitals": int(len(frame)),
        "n_hospitals_at_least_30": int(len(frame)),
        "n_admissions_at_least_30": int(frame["n"].sum()),
        "n_sites_macro_auc_valid": int(len(valid)),
        "n_sites_macro_auc_missing": int(frame["macro_auc"].isna().sum()),
        "n_sites_highest_class_auc_valid": int(
            frame["highest_class_auc"].notna().sum()
        ),
        "site_macro_auc_mean": float(values.mean()),
        "site_macro_auc_sd": float(values.std(ddof=1)),
        "site_macro_auc_q1": q1,
        "site_macro_auc_median": median,
        "site_macro_auc_q3": q3,
        "site_macro_auc_iqr": q3 - q1,
        "site_macro_auc_min": float(values.min()),
        "site_macro_auc_max": float(values.max()),
        "worst_hospital": str(worst["hospital_key"]),
        "worst_hospital_n": int(worst["n"]),
        "worst_hospital_n_high_need": int(worst["n_high_need"]),
        "worst_hospital_macro_auc": float(worst["macro_auc"]),
        "best_hospital": str(best["hospital_key"]),
        "best_hospital_n": int(best["n"]),
        "best_hospital_n_high_need": int(best["n_high_need"]),
        "best_hospital_macro_auc": float(best["macro_auc"]),
    }


def summarize_cluster_holdout(model_audit: dict) -> dict[str, float | int]:
    holdout = model_audit["patient_safe_leave_one_cluster_out"]
    clusters = holdout["sites"]
    require(
        len(clusters) == 147,
        "Patient-safe cluster holdout must contain all 147 clusters",
    )
    deltas = np.asarray(
        [float(row["delta_from_full"]) for row in clusters], dtype=float
    )
    values = np.asarray(
        [float(row["macro_auc_without_site"]) for row in clusters], dtype=float
    )
    return {
        "cluster_holdout_n_clusters": int(len(clusters)),
        "cluster_holdout_full_macro_auc": float(holdout["full_macro_auc"]),
        "cluster_holdout_min_macro_auc": float(holdout["minimum"]),
        "cluster_holdout_max_macro_auc": float(holdout["maximum"]),
        "cluster_holdout_range": float(
            holdout["maximum"] - holdout["minimum"]
        ),
        "cluster_holdout_max_abs_delta": float(
            holdout["largest_absolute_delta"]
        ),
        "cluster_holdout_min_delta": float(deltas.min()),
        "cluster_holdout_max_delta": float(deltas.max()),
        "cluster_holdout_negative_delta_count": int((deltas < 0).sum()),
        "cluster_holdout_positive_delta_count": int((deltas > 0).sum()),
        "cluster_holdout_zero_delta_count": int((deltas == 0).sum()),
        "cluster_holdout_min_macro_auc_recomputed": float(values.min()),
        "cluster_holdout_max_macro_auc_recomputed": float(values.max()),
    }


def summarize_bootstrap(model_audit: dict) -> dict[str, float | int | None]:
    bootstrap = model_audit.get("patient_safe_cluster_bootstrap", {})
    macro = bootstrap.get("macro_auc", {})
    highest_class = bootstrap.get("highest_class_auc", {})
    return {
        "cluster_bootstrap_macro_auc_ci_low": round_or_none(
            macro.get("ci_low")
        ),
        "cluster_bootstrap_macro_auc_ci_high": round_or_none(
            macro.get("ci_high")
        ),
        "cluster_bootstrap_macro_auc_valid_replicates": int(
            macro.get("valid_replicates", 0)
        ),
        "cluster_bootstrap_highest_class_auc_ci_low": round_or_none(
            highest_class.get("ci_low")
        ),
        "cluster_bootstrap_highest_class_auc_ci_high": round_or_none(
            highest_class.get("ci_high")
        ),
        "cluster_bootstrap_highest_class_auc_valid_replicates": int(
            highest_class.get("valid_replicates", 0)
        ),
    }


def summarize_recalibration(model_audit: dict) -> dict[str, float | int | None]:
    recalibration = model_audit.get(
        "patient_safe_cluster_recalibration_high_need",
        {},
    )
    before = recalibration.get("before", {})
    after = recalibration.get("after_cross_fitted", {})
    return {
        "cluster_recalibration_n": int(recalibration.get("n_cross_fitted", 0)),
        "cluster_recalibration_slope_before": round_or_none(before.get("slope")),
        "cluster_recalibration_intercept_before": round_or_none(
            before.get("intercept")
        ),
        "cluster_recalibration_slope_after": round_or_none(after.get("slope")),
        "cluster_recalibration_intercept_after": round_or_none(
            after.get("intercept")
        ),
    }


def build_model_summary(site_table: pd.DataFrame, audit: dict) -> pd.DataFrame:
    models = audit["models"]
    require(
        set(models) == set(MODEL_ORDER),
        f"Unexpected model set in site audit: {sorted(models)}",
    )
    rows = []
    for model in MODEL_ORDER:
        row = {
            "model": model,
            "model_label": MODEL_LABELS[model],
            "is_primary": model == PRIMARY_MODEL,
        }
        row.update(summarize_site_auc(site_table, model))
        row.update(summarize_cluster_holdout(models[model]))
        row.update(summarize_bootstrap(models[model]))
        row.update(summarize_recalibration(models[model]))
        row.update(
            {
                "n_hospitals_all": int(audit["n_hospitals"]),
                "n_hospitals_at_least_30_all": int(
                    audit["n_hospitals_at_least_30"]
                ),
                "n_admissions_at_least_30_all": int(
                    audit["n_admissions_at_least_30"]
                ),
            }
        )
        rows.append(row)
    return pd.DataFrame(rows)


def validate_outputs(
    cohort: pd.DataFrame,
    site_table: pd.DataFrame,
    audit: dict,
    summary: pd.DataFrame,
) -> dict:
    hospital_counts = cohort["hospital_key"].value_counts()
    eligible = hospital_counts.loc[hospital_counts >= 30]
    class_support = pd.crosstab(cohort["hospital_key"], cohort["outcome4"])
    complete_sites = class_support.loc[eligible.index].gt(0).all(axis=1)
    model_counts = site_table.groupby("model").size().to_dict()

    checks = {
        "cohort_rows_equal_6696": int(len(cohort)) == 6696,
        "cohort_hospitals_equal_174": int(hospital_counts.size) == 174,
        "eligible_hospitals_equal_68": int(eligible.size) == 68,
        "eligible_admissions_equal_5688": int(eligible.sum()) == 5688,
        "four_class_support_complete_sites_equal_35": int(
            complete_sites.sum()
        )
        == 35,
        "site_table_models_equal_three": set(model_counts) == set(MODEL_ORDER),
        "site_table_rows_all_equal_68": all(
            count == 68 for count in model_counts.values()
        ),
        "site_table_admissions_all_equal_5688": bool(
            site_table.groupby("model")["n"].sum().eq(5688).all()
        ),
        "audit_model_set_matches_site_table": set(audit["models"])
        == set(model_counts),
        "cluster_holdout_all_equal_147": all(
            len(model["patient_safe_leave_one_cluster_out"]["sites"]) == 147
            for model in audit["models"].values()
        ),
        "patient_safe_cluster_count_equal_147": int(
            audit["patient_safe_hospital_clusters"]["n_hospital_clusters"]
        )
        == 147,
        "patient_safe_clusters_merge_cross_hospital_patients": int(
            audit["patient_safe_hospital_clusters"]["n_cross_hospital_patients"]
        )
        == 33,
        "bootstrap_replicates_all_equal_2000": all(
            value["valid_replicates"] == 2000
            for model in audit["models"].values()
            for value in model["patient_safe_cluster_bootstrap"].values()
        ),
        "summary_has_three_models": len(summary) == 3,
        "summary_primary_model_present": bool(
            summary["model"].eq(PRIMARY_MODEL).any()
        ),
        "no_retraining_performed": True,
    }
    require(all(checks.values()), f"Validation failed: {checks}")
    return {
        "checks": checks,
        "all_passed": True,
        "n_sites_macro_auc_valid": int(complete_sites.sum()),
        "n_sites_macro_auc_missing": int((~complete_sites).sum()),
        "reason_site_macro_auc_missing": (
            "One or more of the four outcome classes has zero admissions at "
            "the hospital, so complete four-class macro-AUC is undefined."
        ),
        "missing_class_pattern_counts": {
            "class_1_only": int(
                class_support.loc[eligible.index, 1].eq(0).sum()
                - class_support.loc[eligible.index, [1, 3]].eq(0).all(axis=1).sum()
            ),
            "classes_1_and_3": int(
                class_support.loc[eligible.index, [1, 3]].eq(0).all(axis=1).sum()
            ),
        },
    }


def to_json_models(summary: pd.DataFrame) -> dict:
    records = {}
    for _, row in summary.iterrows():
        records[str(row["model"])] = {
            key: (
                value.item()
                if isinstance(value, (np.generic,))
                else value
            )
            for key, value in row.to_dict().items()
            if isinstance(value, (str, bool, int, float, np.generic))
            and value is not None
            and not (isinstance(value, float) and not np.isfinite(value))
        }
    return records


def fmt(value: float | int | None, digits: int = 3) -> str:
    if value is None or not np.isfinite(float(value)):
        return "NA"
    return f"{float(value):.{digits}f}"


def write_markdown(summary: pd.DataFrame, validation: dict) -> None:
    primary = summary.loc[summary["model"].eq(PRIMARY_MODEL)].iloc[0]
    lines = [
        "# Table S12. eICU hospital-level heterogeneity and patient-safe cluster holdout",
        "",
        "Locked-result aggregation only; no model was trained or recalibrated.",
        "",
        "| Model | Hospitals | >=30 cases | Admissions in >=30-case sites | Sites with computable macro-AUC | Site macro-AUC median (IQR) | Site range |",
        "|---|---:|---:|---:|---:|---:|---:|",
    ]
    for _, row in summary.iterrows():
        lines.append(
            "| {label} | {n_hosp} | {n30} | {adm30} | {nvalid} | "
            "{median} ({q1}-{q3}) | {vmin}-{vmax} |".format(
                label=row["model_label"],
                n_hosp=int(row["n_hospitals_all"]),
                n30=int(row["n_hospitals_at_least_30_all"]),
                adm30=int(row["n_admissions_at_least_30_all"]),
                nvalid=int(row["n_sites_macro_auc_valid"]),
                median=fmt(row["site_macro_auc_median"]),
                q1=fmt(row["site_macro_auc_q1"]),
                q3=fmt(row["site_macro_auc_q3"]),
                vmin=fmt(row["site_macro_auc_min"]),
                vmax=fmt(row["site_macro_auc_max"]),
            )
        )

    lines.extend(
        [
            "",
            "## Leave-one-cluster-out and patient-safe cluster bootstrap",
            "",
            "| Model | Full macro-AUC | Cluster-holdout range | Maximum absolute change | Cluster-bootstrap macro-AUC (95% CI) | Cluster-bootstrap highest-class AUROC (95% CI) |",
            "|---|---:|---:|---:|---:|---:|",
        ]
    )
    for _, row in summary.iterrows():
        lines.append(
            "| {label} | {full} | {lo}-{hi} | {delta} | "
            "{m_lo}-{m_hi} | {mort_lo}-{mort_hi} |".format(
                label=row["model_label"],
                full=fmt(row["cluster_holdout_full_macro_auc"], 4),
                lo=fmt(row["cluster_holdout_min_macro_auc"], 4),
                hi=fmt(row["cluster_holdout_max_macro_auc"], 4),
                delta=fmt(row["cluster_holdout_max_abs_delta"], 4),
                m_lo=fmt(row["cluster_bootstrap_macro_auc_ci_low"]),
                m_hi=fmt(row["cluster_bootstrap_macro_auc_ci_high"]),
                mort_lo=fmt(
                    row["cluster_bootstrap_highest_class_auc_ci_low"]
                ),
                mort_hi=fmt(
                    row["cluster_bootstrap_highest_class_auc_ci_high"]
                ),
            )
        )

    lines.extend(
        [
            "",
            "## Primary-model hospital extremes",
            "",
            f"- Worst performing eligible site: **{primary['worst_hospital']}**, "
            f"n={int(primary['worst_hospital_n'])}, high-need="
            f"{int(primary['worst_hospital_n_high_need'])}, macro-AUC "
            f"{fmt(primary['worst_hospital_macro_auc'])}.",
            f"- Best performing eligible site: **{primary['best_hospital']}**, "
            f"n={int(primary['best_hospital_n'])}, high-need="
            f"{int(primary['best_hospital_n_high_need'])}, macro-AUC "
            f"{fmt(primary['best_hospital_macro_auc'])}.",
            f"- Leave-one-cluster-out changed the pooled macro-AUC in "
            f"{int(primary['cluster_holdout_negative_delta_count'])} clusters "
            f"negatively and "
            f"{int(primary['cluster_holdout_positive_delta_count'])} clusters "
            "positively; "
            "the sign of each estimate is retained as estimated.",
            "",
            "## Notes",
            "",
            "- eICU contains 174 hospitals. Sixty-eight hospitals contributed "
            "at least 30 admissions, totalling 5,688 admissions.",
            "- Site macro-AUC is shown only for the 35 eligible hospitals in "
            "which all four outcome classes were observed. In the other 33 "
            "hospitals, complete four-class macro-AUC is undefined; missing "
            "values were not imputed and these hospitals were not used in the "
            "distribution or IQR calculation.",
            "- Site macro-AUC values are unweighted descriptive estimates among "
            "eligible hospitals with complete class support. The median and "
            "IQR are therefore hospital-level summaries, not pooled-patient "
            "performance.",
            "- eICU contains 174 hospitals but 33 patients contribute to more "
            "than one hospital. Connected components of the patient-hospital "
            "graph therefore define 147 patient-safe hospital clusters.",
            "- Cluster holdout omits one complete patient-safe cluster from "
            "the fixed locked predictions without retraining. The full, "
            "minimum, and maximum values are pooled-patient macro-AUCs.",
            "- The cluster bootstrap resamples the 147 patient-safe clusters "
            "with replacement (2,000 replicates) and retains the locked "
            "predictions. These intervals differ from the patient-bootstrap "
            "intervals in the main external-validation table.",
            "- Hospital identifiers are anonymized source keys (`eicu_NNN`). "
            "Negative cluster-holdout changes are retained and are not "
            "converted to positive values.",
            "- High-need recalibration is cross-fitted by patient-safe "
            "hospital cluster and is reported in the JSON audit.",
            "",
            "Validation: "
            + (
                "all checks passed."
                if validation["all_passed"]
                else "FAILED."
            ),
        ]
    )
    MD_PATH.write_text("\n".join(lines) + "\n", encoding="utf-8")


def main() -> None:
    cohort = pd.read_csv(COHORT_PATH)
    site_table = pd.read_csv(SITE_METRICS_PATH)
    audit = json.loads(SITE_AUDIT_PATH.read_text(encoding="utf-8"))

    summary = build_model_summary(site_table, audit)
    validation = validate_outputs(cohort, site_table, audit, summary)

